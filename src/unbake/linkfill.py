"""The linker's alignment fill: the stale bytes an older link left between objects, modelled as part of the link.

The linker that built a ROM rounded each object up to the alignment of the next and filled the gap with whatever the
link before it held there, not with zeros. Ours fills a gap with zeros, so those bytes need a producer that is neither
a source file nor a pad array: a fill record. `versions/<v>/linker_fill.toml` holds one `[[fill]]` row per gap whose
bytes are not all zero (a zero gap needs no record: the link already leaves zeros). The file is generated by
`unbake layout fill` from the ROM and the object plan, never written by hand. A row has
  object      the object plan's index of the object whose alignment fill the gap is
  section     the plan's section of the gap
  rom         the ROM offset of the first byte, address the address of it, size the length
  bytes       the exact bytes, hex
  provenance  `earlier-link 0x<rom>` where the same bytes sit once in the older link the version carries (an
              earlier-build window), else `unattributed`; several places claim nothing
The link script emits each row right where its bytes lie in the segment (`statement`), and the splat file cuts the
bytes into a piece of their own (`piece`), so neither a function nor a data object before them owns the gap."""

from __future__ import annotations

import itertools
import tomllib
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from unbake import config as configuration
from unbake import effort, objectplan, versions, windows
from unbake.contracts import Config, Finding, Json, Refusal

PAD_KIND = "pad"  # the plan's kind of an alignment pad
UNATTRIBUTED = "unattributed"
EARLIER = "earlier-link"
_KEYS = frozenset({"object", "section", "rom", "address", "size", "bytes", "provenance"})


@dataclass(frozen=True)
class Fill:
    object: str
    section: str
    rom: int
    address: int
    data: bytes
    provenance: str = UNATTRIBUTED

    @property
    def size(self) -> int:
        return len(self.data)


def path(version: str) -> str:
    return f"versions/{version}/linker_fill.toml"


def _refuse(version: str, reason: str, **more: object) -> Refusal:
    return Refusal(Finding("fill.record", f"{version}: {reason}", path=path(version), versions=(version,), **more))  # type: ignore[arg-type]


def parse(text: str, version: str) -> list[Fill]:
    """The rows of one version's fill file, in ROM order. A row that lacks a field, carries an unknown one, holds
    bytes that are not `size` hex bytes or all zeros, or overlaps the row before it is refused."""
    doc = tomllib.loads(text)
    if doc.get("version", version) != version:
        raise _refuse(version, f"the file is for {doc['version']}")
    rows: list[Fill] = []
    for i, row in enumerate(doc.get("fill", ()), 1):
        if bad := (_KEYS - row.keys()) or (row.keys() - _KEYS):
            raise _refuse(version, f"fill row {i} has the wrong fields: {', '.join(sorted(bad))}")
        try:
            data = bytes.fromhex(row["bytes"])
        except ValueError:
            raise _refuse(version, f"fill row {i}: bytes is not hex") from None
        if len(data) != row["size"] or not any(data):
            raise _refuse(
                version, f"fill row {i} at 0x{row['rom']:X}: size {row['size']} is not the {len(data)} nonzero bytes"
            )
        rows.append(Fill(str(row["object"]), row["section"], row["rom"], row["address"], data, row["provenance"]))
    rows.sort(key=lambda f: f.rom)
    for before, row in itertools.pairwise(rows):
        if before.rom + before.size > row.rom:
            raise _refuse(version, f"fill rows at 0x{before.rom:X} and 0x{row.rom:X} overlap")
    return rows


def read_text(root: Path, version: str) -> str:
    """The text of a version's fill file; empty when the project has no file for it."""
    file = root / path(version)
    return file.read_text() if file.is_file() else ""


def read(root: Path, version: str) -> list[Fill]:
    """The fill rows of a version; none when the project has no file for it."""
    text = read_text(root, version)
    return parse(text, version) if text else []


def render(version: str, fills: Iterable[Fill], generator: str) -> str:
    """The text of a version's fill file."""
    out = [f"# {generator}", f'version = "{version}"']
    for f in sorted(fills, key=lambda f: f.rom):
        out += [
            "",
            "[[fill]]",
            f'object = "{f.object}"',
            f'section = "{f.section}"',
            f"rom = 0x{f.rom:X}",
            f"address = 0x{f.address:08X}",
            f"size = {f.size}",
            f'bytes = "{f.data.hex()}"',
            f'provenance = "{f.provenance}"',
        ]
    return "\n".join(out) + "\n"


def statement(fill: Fill, start: int) -> str:
    """The link script line of one row in a segment that starts at ROM offset `start`: the location counter moves to
    the bytes (never back: a gap that an object's bytes already reach refuses to link) and each byte is emitted; the
    script's own `;` ends the last one."""
    return f". = 0x{fill.rom - start:X}; " + "; ".join(f"BYTE(0x{b:02X})" for b in fill.data)


def piece(fill: Fill, segment: str) -> tuple[int, str, str]:
    """The splat cell of one row: (rom, type, `<segment>/fill_<ROM>`), the type the extractor gives a data piece."""
    return (fill.rom, "data", f"{segment}/fill_{fill.rom:X}")


def rom_of(pieces: Sequence[tuple[str, int, int, int]], address: int) -> int | None:
    """The ROM offset of a RAM address in the pieces (name, rom start, rom end, vram); None when no piece or more than
    one piece holds it."""
    found = [start + address - vram for _, start, end, vram in pieces if vram <= address < vram + end - start]
    return found[0] if len(found) == 1 else None


def earlier_link(data: bytes, windows: Sequence[tuple[int, bytes]]) -> str:
    """`earlier-link 0x<rom>` when the bytes occur exactly once in the older link's windows (rom start, image), else
    `unattributed`."""
    hits = [start + i for start, image in windows for i in _finds(image, data)]
    return f"{EARLIER} 0x{hits[0]:X}" if len(hits) == 1 else UNATTRIBUTED


def _finds(image: bytes, data: bytes) -> Iterable[int]:
    at = image.find(data)
    while at >= 0:
        yield at
        at = image.find(data, at + 1)


def build(
    atoms: Iterable[tuple[str, str, int, int, int]], rom: bytes, windows: Sequence[tuple[int, bytes]]
) -> list[Fill]:
    """The rows for the gaps `atoms` (object, section, address, rom offset, size) name in one ROM: a zero gap gets
    none."""
    rows = []
    for obj, section, address, at, size in atoms:
        data = rom[at : at + size]
        if any(data):
            rows.append(Fill(obj, section, at, address, data, earlier_link(data, windows)))
    return sorted(rows, key=lambda f: f.rom)


def generate(config: Config, params: Json) -> dict[str, Any]:
    """`unbake layout fill --plan FILES.tsv`: write `versions/<v>/linker_fill.toml` of every version from its ROM and
    the plan's pad atoms (OBJECTS.tsv and ASSIGN.tsv beside FILES.tsv). A version with no nonzero pad atom has no
    file: one left from an earlier run is removed. A pad atom no piece of the version holds is refused."""
    with effort.stage("layout.fill"):
        files = Path(str(params["plan"]))
        missing = [
            str(f) for f in (files, files.parent / "OBJECTS.tsv", files.parent / "ASSIGN.tsv") if not f.is_file()
        ]
        if missing:
            raise Refusal(
                Finding(
                    "fill.plan",
                    "fill --plan needs FILES.tsv with OBJECTS.tsv and ASSIGN.tsv beside it",
                    missing=tuple(missing),
                )
            )
        plan = objectplan.read_dir(files)
        project = config.project
        out: dict[str, Any] = {"action": "fill", "versions": {}, "written": []}
        for v in project.versions:
            pieces = versions.pieces(config, v)
            rom = configuration.rom(project, v).read_bytes()
            atoms = []
            for (version, section), rows in sorted(plan.atoms.items()):
                for a in (a for a in rows if version == v and a.kind == PAD_KIND):
                    at = rom_of(pieces, a.address)
                    if at is None:
                        raise Refusal(
                            Finding(
                                "fill.plan",
                                f"{v}: the pad atom at 0x{a.address:08X} lies in no single piece",
                                versions=(v,),
                            )
                        )
                    atoms.append((str(a.object), section, a.address, at, a.size))
            earlier = [
                (start, rom[start:end])
                for segment, (_, start, end, _) in zip(project.version[v].segments, pieces, strict=True)
                if segment.address_space == windows.SPACE
            ]
            fills = build(atoms, rom, earlier)
            target = project.root / path(v)
            if fills:
                target.write_text(
                    render(v, fills, "generated by `unbake layout fill` from the ROM and the object plan; do not edit")
                )
                out["written"].append(path(v))
            else:
                target.unlink(missing_ok=True)
            out["versions"][v] = {"fills": len(fills), "bytes": sum(f.size for f in fills)}
        return out
